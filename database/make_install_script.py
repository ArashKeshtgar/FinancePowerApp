"""Builds database/install/erp_install.sql: every numbered script except the demo seed, in one file that SSMS (or
the Azure Portal's Query editor) can run as is, for a database where deploy.ps1 can't be used.

All of it runs in one transaction. A failing batch rolls it back (XACT_ABORT), and the guard between batches then
turns off execution for the rest, so the database is either fully upgraded or untouched. Each script is recorded in
dbo.ErpMigration, so deploy.ps1 skips it later. Run again after the ERP is installed, it does nothing.

    python3 database/make_install_script.py
"""
import pathlib
import re

here = pathlib.Path(__file__).parent
scripts = sorted(p for p in here.glob("*.sql") if re.match(r"^\d{3}_", p.name) and not p.name.endswith("_seed_demo.sql"))

GUARD = "IF @@TRANCOUNT = 0 BEGIN PRINT N'*** Stopped: an error above rolled everything back. Nothing was changed. ***'; SET NOEXEC ON; END\nGO\n"

out = [f"""-- FinancePowerApp ERP install: {', '.join(p.name for p in scripts)}.
-- GENERATED by database/make_install_script.py from those files; don't edit by hand.
--
-- Open in SSMS connected to the target database (not master), then Execute (F5). Staging first.
-- One transaction: on any error, everything rolls back and the rest is skipped ("Stopped" in Messages). The error
-- just above "Stopped" is the cause; errors after it only come from the skipped steps.
-- Already installed: does nothing.

SET XACT_ABORT ON;
SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO
DECLARE @installed int = 0;
IF OBJECT_ID(N'dbo.ErpMigration', N'U') IS NOT NULL
    EXEC sp_executesql N'SELECT @n = COUNT(*) FROM dbo.ErpMigration WHERE Script = N''010_erp_schema.sql''', N'@n int OUTPUT', @installed OUTPUT;
IF @installed > 0
BEGIN
    PRINT N'*** The ERP is already installed here. Nothing was changed. ***';
    SET NOEXEC ON;
END
GO
BEGIN TRANSACTION;
GO
IF OBJECT_ID(N'dbo.ErpMigration', N'U') IS NULL
    CREATE TABLE dbo.ErpMigration (Script nvarchar(200) NOT NULL PRIMARY KEY, AppliedUtc datetime2(3) NOT NULL DEFAULT SYSUTCDATETIME());
GO
"""]

for p in scripts:
    out.append(f"\n-- ===== {p.name} =====\n")
    for batch in re.split(r"^\s*GO\s*$", p.read_text(encoding="utf-8"), flags=re.M | re.I):
        if batch.strip():
            out.append(GUARD + batch.strip("\n") + "\nGO\n")
    out.append(GUARD + f"IF NOT EXISTS (SELECT 1 FROM dbo.ErpMigration WHERE Script = N'{p.name}') INSERT dbo.ErpMigration (Script) VALUES (N'{p.name}');\nGO\n")

out.append("\n" + GUARD + "COMMIT;\nPRINT N'*** ERP installed. ***';\nGO\nSET NOEXEC OFF;\nGO\n")

target = here / "install" / "erp_install.sql"
target.parent.mkdir(exist_ok=True)
target.write_text("".join(out), encoding="utf-8")
print(f"{target.relative_to(here.parent)}: {len(scripts)} scripts")
